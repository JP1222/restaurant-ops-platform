#!/usr/bin/env node
// Sync the AI usage-cost price table from LiteLLM's community price oracle.
//
// LiteLLM's `model_prices_and_context_window.json` is the de-facto shared price map
// (tokencost, tokonomics, et al. consume it). We treat price data as a commodity: this
// script fetches it, extracts the per-1M input / cache-read / output rates for the
// catalog keys our app actually uses (the VALUES in model-aliases.json), and writes the
// vendored subset to model-prices.generated.json. The file is committed so the runtime
// and the build never touch the network; rerun this when prices may have moved (e.g.
// before a deploy). Hand-edits are overwritten — pin contract rates in PRICE_OVERRIDES
// (apps/backoffice-web/lib/ai/model-prices.ts) instead.
import { readFileSync, writeFileSync, renameSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");

// Overridable so a pinned mirror can be used (matches LiteLLM's own LITELLM_MODEL_COST_MAP_URL).
const LITELLM_URL =
  process.env.LITELLM_MODEL_COST_MAP_URL ??
  "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";

const ALIASES_PATH = path.join(rootDir, "apps/backoffice-web/lib/ai/model-aliases.json");
const OUTPUT_PATH = path.join(rootDir, "apps/backoffice-web/lib/ai/model-prices.generated.json");

// Convert one LiteLLM catalog entry (costs are per-TOKEN) to our per-1M ModelPrice shape.
// Returns null when the entry lacks the basic input/output costs we price on, so the
// caller skips it and reports it missing rather than emitting a misleading $0. The
// cache-read rate is optional (many entries omit it). Exported for unit tests.
export function litellmEntryToPrice(entry) {
  if (!entry || typeof entry !== "object") return null;
  const input = entry.input_cost_per_token;
  const output = entry.output_cost_per_token;
  if (typeof input !== "number" || typeof output !== "number") return null;
  // per-token → per-1M, trimming float noise (2.5e-8 * 1e6 = 0.024999…998) to keep the
  // committed JSON stable and readable. 10 dp is far finer than any real list price.
  const per1M = (perToken) => Number((perToken * 1_000_000).toFixed(10));
  const price = {
    inputPer1M: per1M(input),
    outputPer1M: per1M(output),
  };
  const cacheRead = entry.cache_read_input_token_cost;
  if (typeof cacheRead === "number") {
    price.cachedInputPer1M = per1M(cacheRead);
  }
  return price;
}

async function main() {
  const aliases = JSON.parse(readFileSync(ALIASES_PATH, "utf8"));
  const wantedKeys = [...new Set(Object.values(aliases))].sort();

  console.log(`Fetching LiteLLM price map: ${LITELLM_URL}`);
  const res = await fetch(LITELLM_URL, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) {
    console.error(`Fetch failed: HTTP ${res.status} ${res.statusText}`);
    process.exit(1);
  }
  const catalog = await res.json();

  const prices = {};
  const missing = [];
  for (const key of wantedKeys) {
    const price = litellmEntryToPrice(catalog[key]);
    if (price) {
      prices[key] = price;
    } else {
      missing.push(key);
    }
  }

  // Don't silently drop coverage: a mapped key the catalog no longer carries must be
  // visible so the operator knows it needs a PRICE_OVERRIDE (or reads as unpriced).
  if (missing.length > 0) {
    console.warn(
      `\n⚠ ${missing.length} mapped key(s) absent from the LiteLLM catalog — add a PRICE_OVERRIDE or they read as unpriced:`,
    );
    for (const key of missing) console.warn(`   • ${key}`);
    console.warn("");
  }

  const payload = {
    _source: `${LITELLM_URL} — generated by \`pnpm ai:prices:sync\`; do not hand-edit (use PRICE_OVERRIDES). USD per 1,000,000 tokens.`,
    prices: Object.fromEntries(Object.entries(prices).sort(([a], [b]) => a.localeCompare(b))),
  };

  const tmp = `${OUTPUT_PATH}.tmp`;
  writeFileSync(tmp, `${JSON.stringify(payload, null, 2)}\n`);
  renameSync(tmp, OUTPUT_PATH);
  console.log(
    `Wrote ${Object.keys(prices).length}/${wantedKeys.length} model price(s) → ${path.relative(rootDir, OUTPUT_PATH)}`,
  );
}

// Only auto-run when invoked directly (`node scripts/ai-prices-sync.mjs`), so test files
// can import litellmEntryToPrice without triggering the network fetch.
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  await main();
}
