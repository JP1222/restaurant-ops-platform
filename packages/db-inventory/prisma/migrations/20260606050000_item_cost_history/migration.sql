-- Effective-dated per-usage cost history for inventory items (ADR-0573 follow-up).
--
-- The count-based actual-COGS valuation reconstructs on-hand at a past count from
-- the stock ledger and values it at item cost. v1 used the *current* cost, so a
-- later cost edit re-priced every past (closed) window. This table records the cost
-- effective at each point in time, so the valuation can value each count at the cost
-- effective THEN — a closed between-count window is frozen and a future edit can no
-- longer move its actual COGS / yield variance.
--
-- Append-only, maintained by a trigger on inventory_items so EVERY cost-write path
-- (catalog create/edit, ad-hoc-receive item create, BOM import, and any future path)
-- is captured with no per-call-site code. id is DB-generated so the trigger inserts
-- without an app-side cuid.

CREATE TABLE "inventory_item_cost_history" (
    "id"             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "item_id"        TEXT NOT NULL,
    "cost_cents"     DOUBLE PRECISION NOT NULL,
    "effective_from" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "inventory_item_cost_history_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "inventory_item_cost_history_item_id_effective_from_idx"
    ON "inventory_item_cost_history" ("item_id", "effective_from");

-- Append a history row whenever an item's per-usage cost is first set (INSERT) or
-- changes (UPDATE). IS DISTINCT FROM is NULL-safe; cost_cents is NOT NULL here, but
-- the guard stays correct regardless and skips no-op updates that leave cost untouched.
CREATE OR REPLACE FUNCTION "record_inventory_item_cost_history"()
RETURNS trigger AS $$
BEGIN
    IF (TG_OP = 'INSERT') OR (NEW."cost_cents" IS DISTINCT FROM OLD."cost_cents") THEN
        INSERT INTO "inventory_item_cost_history" ("item_id", "cost_cents", "effective_from")
        VALUES (NEW."id", NEW."cost_cents", CURRENT_TIMESTAMP);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "inventory_item_cost_history_trg"
    AFTER INSERT OR UPDATE OF "cost_cents" ON "inventory_items"
    FOR EACH ROW EXECUTE FUNCTION "record_inventory_item_cost_history"();

-- Baseline: one row per existing item at its current cost, effective from the item's
-- creation. Pre-migration cost edits aren't recoverable, so the baseline reproduces
-- today's current-cost behavior — but freezing it here means future edits no longer
-- re-price closed windows. Writes the history table directly, so the trigger above
-- (on inventory_items) does not fire for it.
INSERT INTO "inventory_item_cost_history" ("item_id", "cost_cents", "effective_from")
SELECT "id", "cost_cents", "createdAt" FROM "inventory_items";
